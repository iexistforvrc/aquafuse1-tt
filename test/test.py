"""AquaFuse-1 (stream12c) known-answer tests, run by Tiny Tapeout's `test` and `gl_test` actions.

The vectors are REAL held-out herring frames from `vectors/` (generated by
physical/gemm12/regen_stream12c.py from the part's oracle, never from this RTL):
  chip12c_frames.hex  32 frames x 54 x 96 unsigned bytes
  chip12c_logit.hex   the oracle's max-cell logit per frame (32-bit two's complement)
  chip12c_shaped.hex  the oracle's wake bit (3-of-11 popcount, hold 10) per frame
The raw alarm per frame is `logit + CLS_OFFSET >= 0`, CLS_OFFSET read from src/aquafuse_chip.svh.

The same file runs against the RTL (Icarus) and against the hardened netlist (GATES=yes).
AQUAFUSE_FRAMES sets how many frames test_golden_frames drives (default 32; the Makefile sets 12 for the RTL run,
which is slow in Icarus, and leaves 32 for the gate-level run).
"""
import os
import re
from pathlib import Path

import cocotb
from cocotb.clock import Clock
from cocotb.triggers import ClockCycles

HERE = Path(__file__).resolve().parent
VEC = HERE / "vectors"
SRC = HERE.parent / "src"
IMG_H, IMG_W = 54, 96
PCLK_DIV = 2          # 2 core clocks low + 2 high per pixel = 4 clocks per pixel (the tested rate)
# The result_valid pulse arrives about 1,024 clocks after a frame's last pixel (measured on the r8/r9
# netlist traces), so each frame is followed by this many sampled idle clocks: the result of frame f is
# read before frame f+1 starts. (The RTL testbench's 269-clock minimum gap lets results slide into the next
# frame; both are legal for the chip, this one makes the per-frame check simple.)
T_SETTLE = 1500
N_FRAMES = int(os.environ.get("AQUAFUSE_FRAMES", "32"))
CFG_W = 42

VS, PCLK, CFG_SCK, CFG_SDI, CFG_LOAD = 1 << 1, 1 << 0, 1 << 2, 1 << 3, 1 << 4
ALARM, RESULT_VALID, OVERRUN, DETECT, OVERRUN_FRAME, CFG_SDO, CFG_LOADED, RESYNCED = (1 << i for i in range(8))


def _words(path):
    return path.read_text().split()


def load_vectors():
    frames = [int(w, 16) for w in _words(VEC / "chip12c_frames.hex")]
    logits = [int(w, 16) for w in _words(VEC / "chip12c_logit.hex")]
    logits = [v - (1 << 32) if v >= (1 << 31) else v for v in logits]
    shaped = [int(w) for w in _words(VEC / "chip12c_shaped.hex")]
    m = re.search(r"CLS_OFFSET\s*=\s*(-?)32'sd(\d+)", (SRC / "aquafuse_chip.svh").read_text())
    offset = -int(m.group(2)) if m.group(1) else int(m.group(2))
    mn = re.search(r"SHAPE_M\s*=\s*5'd(\d+)", (SRC / "aquafuse_chip.svh").read_text())
    nn = re.search(r"SHAPE_N\s*=\s*5'd(\d+)", (SRC / "aquafuse_chip.svh").read_text())
    return frames, logits, shaped, offset, int(mn.group(1)), int(nn.group(1))


def pins(signal):
    try:
        return int(signal.value)
    except ValueError:
        return None   # X or Z: the caller treats it as a failure


async def reset(dut):
    dut.ena.value = 1
    dut.ui_in.value = 0
    dut.uio_in.value = 0
    dut.rst_n.value = 0
    await ClockCycles(dut.clk, 10)
    dut.rst_n.value = 1
    await ClockCycles(dut.clk, 6)


async def drive_frame(dut, frames, f):
    """One frame exactly as tb_stream12c_logit drives it; returns (alarm, detect, overrun_bits) at result_valid."""
    dut.uio_in.value = VS
    await ClockCycles(dut.clk, 6)
    base = f * IMG_H * IMG_W
    for i in range(IMG_H * IMG_W):
        await ClockCycles(dut.clk, PCLK_DIV)
        dut.ui_in.value = frames[base + i]
        dut.uio_in.value = VS | PCLK
        await ClockCycles(dut.clk, PCLK_DIV)
        dut.uio_in.value = VS
    await ClockCycles(dut.clk, 8)
    dut.uio_in.value = 0
    pulses, got, prev = 0, None, 0
    for _ in range(T_SETTLE):
        await ClockCycles(dut.clk, 1)
        uo = pins(dut.uo_out)
        assert uo is not None, "uo_out has X/Z after reset"
        if (uo & RESULT_VALID) and not (prev & RESULT_VALID):
            pulses += 1
            got = (int(bool(uo & ALARM)), int(bool(uo & DETECT)), uo & (OVERRUN | OVERRUN_FRAME))
        prev = uo
    assert pulses == 1, f"frame {f}: {pulses} result_valid pulses, expected 1"
    return got


async def start(dut):
    cocotb.start_soon(Clock(dut.clk, 10, unit="us").start())
    await reset(dut)


@cocotb.test()
async def test_golden_frames(dut):
    """RTL (or netlist) == oracle on real frames: one result per frame, raw alarm and wake bit as the oracle says."""
    frames, logits, shaped, offset, _, _ = load_vectors()
    await start(dut)
    n = min(N_FRAMES, len(shaped))
    mismatches, alarms, wakes = [], 0, 0
    for f in range(n):
        alarm, detect, over = await drive_frame(dut, frames, f)
        want_alarm = int(logits[f] + offset >= 0)
        alarms += alarm
        wakes += detect
        if (alarm, detect) != (want_alarm, shaped[f]) or over:
            mismatches.append((f, (alarm, detect, over), (want_alarm, shaped[f])))
    dut._log.info(f"{n} frames: {alarms} raw alarms, {wakes} wake bits; mismatches {mismatches}")
    assert not mismatches, f"frame results differ from the oracle: {mismatches}"
    # a shortened run must still reach the decision: the clip first alarms at frame 5 and the wake bit first rises at frame 7
    assert sum(int(logits[f] + offset >= 0) for f in range(n)) >= 1, "AQUAFUSE_FRAMES is too small to reach the first alarm"
    assert alarms >= 1, "the chip never raised the raw alarm"
    if sum(shaped[:n]) >= 1:
        assert wakes >= 1, "the chip never raised the wake bit"


async def shift_cfg(dut, word=None):
    """Clock 42 config bits MSB first; with word=None shift zeros. Returns the bits seen on cfg_sdo before each edge."""
    seen = 0
    for k in range(CFG_W - 1, -1, -1):
        bit = 0 if word is None else (word >> k) & 1
        sdo = pins(dut.uo_out)
        assert sdo is not None
        seen = (seen << 1) | int(bool(sdo & CFG_SDO))
        dut.uio_in.value = bit * CFG_SDI
        await ClockCycles(dut.clk, 4)
        dut.uio_in.value = bit * CFG_SDI | CFG_SCK
        await ClockCycles(dut.clk, 6)
        dut.uio_in.value = bit * CFG_SDI
        await ClockCycles(dut.clk, 4)
    dut.uio_in.value = 0
    await ClockCycles(dut.clk, 4)
    return seen


async def load_cfg(dut):
    dut.uio_in.value = CFG_LOAD
    await ClockCycles(dut.clk, 6)
    dut.uio_in.value = 0
    await ClockCycles(dut.clk, 8)


@cocotb.test()
async def test_config_path(dut):
    """The 42-bit config word: default readback, load, readback, and the threshold really moves the decision."""
    frames, logits, shaped, offset, m, n = load_vectors()
    await start(dut)
    default = (m << 37) | (n << 32) | (offset & 0xFFFFFFFF)
    assert await shift_cfg(dut) == default, "cfg_sdo read-back of the reset config differs from the generated constants"
    assert not (pins(dut.uo_out) & CFG_LOADED), "cfg_loaded must be low before a load"
    first = next(f for f in range(len(shaped)) if logits[f] + offset >= 0)   # first frame the oracle alarms on
    never = (m << 37) | (n << 32) | ((-(1 << 30)) & 0xFFFFFFFF)
    always = (m << 37) | (n << 32) | ((1 << 30) & 0xFFFFFFFF)
    await shift_cfg(dut, never)
    await load_cfg(dut)
    assert pins(dut.uo_out) & CFG_LOADED, "cfg_loaded must go high after CFG_LOAD with no frame in flight"
    assert await shift_cfg(dut) == never, "cfg_sdo read-back after load differs from the word written"
    for f in range(first + 1):
        alarm, _, over = await drive_frame(dut, frames, f)
        assert alarm == 0 and not over, f"frame {f}: threshold -2^30 must suppress every alarm"
    await shift_cfg(dut, always)
    await load_cfg(dut)
    alarm, _, over = await drive_frame(dut, frames, first + 1)
    assert alarm == 1 and not over, "threshold +2^30 must alarm on every frame"
