`timescale 1ns/1ps
// AquaFuse-1 streaming top: sensor-direct, companion-free.
//
// Phase 2.4 and 2.5 of the companion-free plan. What is GONE relative to
// tt_um_aquafuse_pbwrb12_prefreeze, measured by synthesis rather than assumed:
//
//   companion protocol block   701 flops   -- there is no companion to talk to
//   activation tile buffer   1,536 flops   -- streaming re-reads nothing, so
//                                             there is nothing to replay
//
// The buffer existed because the GEMM schedule re-sent each activation once per
// COUT-wide block of output channels. A streaming dataflow visits every pixel
// exactly once, in raster order, so the re-send it was built to avoid does not
// occur. capture/replay, the burst protocol and the weight-streaming path go
// with it.
//
// What replaces them is smaller: line stores sized by the arm, and an FSM per
// stage that runs when its rows are ready. Each stage is self-timed off its own
// input, so there is no central schedule and nothing to emit.
//
// Wired for gq54s8_1ch_n6 -- 54x96 mono in, stride-8 stem to 7x13x4, two 3x3
// stride-2 stages to 4x7x6 and 2x4x8, global average pool, 8->1 classifier.
// Every dimension is a parameter; the arm is a configuration, not a rewrite.
//
// PRE-FREEZE, NON-MANUFACTURING. Not D3/D4/D5 exit evidence; decision 0009.
// STREAM12C (DR 0093): stream12b made to compute the model it carries.
// Three differences from 12b, each a defect of 12b found by scoring the part
// end to end (DR 0091, DR 0092, DEFECT_REGISTER DR005/DR007):
//   * an EMA of the stem accumulator (aquafuse_bg_store) is subtracted before
//     the stem's requantisation, so the stem sees frame minus background --
//     the input the model was trained on -- instead of the raw byte;
//   * every accumulator starts at its folded batch-norm bias;
//   * the alarm the host wakes on (uo_out[3]) is the M-of-SHAPE_N popcount the
//     accuracy was MEASURED with, not a median that was never built.
// Every constant comes from aquafuse_chip.svh and the ROMs, both generated by
// physical/gemm12/regen_stream12c.py from ONE checkpoint through
// host/aquafuse/stream/chip_stream.py -- the oracle the testbench scores
// against. Model -> oracle -> RTL, never RTL -> oracle.
module tt_um_aquafuse_stream12c #(
    parameter int IMG_H  = 54,
    parameter int IMG_W  = 96,
    parameter int IN_CH  = 1,
    parameter int STEM_K = 8,
    parameter int STEM_S = 8,
    parameter int STEM_C = 4,
    parameter int B1_CH  = 6,
    parameter int B2_CH  = 6
) (
    input  wire [7:0] ui_in,
    output wire [7:0] uo_out,
    input  wire [7:0] uio_in,
    output wire [7:0] uio_out,
    output wire [7:0] uio_oe,
    input  wire       ena,
    input  wire       clk,
    input  wire       rst_n
);
// No `include "aquafuse_round.svh" here: the top does no requantisation of its
// own -- each stage requantises its own output -- and merely ELABORATING the
// unused function in this module's context tripped a yosys frontend assert
// (genrtlil.cc:2214, is_signed mismatch). Included only where it is called.
//
// The requantisation shifts themselves ARE included, as pure localparams.
`include "aquafuse_chip.svh"

    // REQUANTISATION SHIFTS, one PER OUTPUT CHANNEL, GENERATED into
    // aquafuse_shifts.svh by physical/gemm12/derive_shifts.py from the
    // DEPLOY weights' own scales. Not chosen for a unit test, and not
    // hand-copied from a fold model.
    //
    // Two separate errors this replaces. (1) A single shift per LAYER measures
    // A2 = 0.8743; per channel measures 0.8905 and clears the 0.89 bar.
    // (2) The constants previously here (stem 8, b1 10, b2 8) were derived from
    // a FOLD model while the ROMs carry DEPLOY, whose stem shifts are 10-11 --
    // the stem therefore ran 4-8x large and saturated at +-127.
    //
    // These are per-MODEL configuration, not design constants: the shifts move
    // with the trained weights, and FW-3 has to make them writable.

    localparam int PAD_S  = STEM_K / 2;
    localparam int S_OH   = (IMG_H + 2*PAD_S - STEM_K)/STEM_S + 1;   // 7
    localparam int S_OW   = (IMG_W + 2*PAD_S - STEM_K)/STEM_S + 1;   // 13
    localparam int B1_OH  = (S_OH + 2 - 3)/2 + 1;                    // 4
    localparam int B1_OW  = (S_OW + 2 - 3)/2 + 1;                    // 7
    // STRIDE 1: the grid does NOT halve here. (B1_OH + 2 - 3)/1 + 1 == B1_OH,
    // so the head sees 4x7 = 28 positions instead of 2x4 = 8. That is the whole
    // point of the compact arm -- a coarser head on a finer grid -- and it is
    // what DR 0070 recommends and ebe7587 made the stage correct for.
    localparam int B2_OH  = B1_OH;                                   // 4
    localparam int B2_OW  = B1_OW;                                   // 7
    localparam int STEM_ACC_W = 21;
    localparam int POOL_W     = 20;

    // PIN MAP.
    //   uio_in[0] PCLK      uio_in[1] VSYNC     -- the sensor, free-running
    //   uio_in[2] CFG_SCK   uio_in[3] CFG_SDI   uio_in[4] CFG_LOAD  -- FW-3
    //   uio_in[7:5] unused
    //   uo_out[0] alarm (raw)       uo_out[1] result_valid
    //   uo_out[2] overrun_sticky    uo_out[3] detect (shaped)
    //   uo_out[4] overrun_frame     uo_out[5] cfg_sdo   uo_out[6] cfg_loaded
    //   uo_out[7] unused
    /* verilator lint_off UNUSEDSIGNAL */
    wire unused = ena & (|uio_in[7:5]);
    /* verilator lint_on UNUSEDSIGNAL */

    reg [1:0] rsync;
    always @(posedge clk or negedge rst_n)
        if (!rst_n) rsync <= 2'b00; else rsync <= {rsync[0], 1'b1};
    wire rstn = rsync[1];

    // ---- FW-3: the per-model constants, LOADABLE --------------------------
    //
    // WHY THIS IS NOT OPTIONAL. The requantisation shifts and CLS_OFFSET are
    // per-MODEL configuration, not design constants: they move with the trained
    // weights, and CLS_OFFSET is the DECISION BOUNDARY itself. Baked as
    // localparams -- which is how they shipped until 6 Sep -- there was no way
    // to move the operating point at all without a new mask.
    //
    // WHAT THIS DOES NOT DO, stated here because it is easy to overclaim and I
    // did. The WEIGHTS are still in ROM: 904 bytes, 7,232 bits, which is not a
    // shift register that fits on this die. So a retrain that changes weights
    // is STILL a respin. What is now free is RE-CALIBRATION -- the decision
    // boundary and the requantisation shifts -- which is what a deployment at a
    // different site, or against a different false-alarm budget, actually
    // needs. Half the problem, and the half that recurs.
    //
    // WHAT IS LOADABLE, AND WHY THE SHIFTS ARE NOT. The first version of this
    // block carried the requantisation shifts too -- 137 bits, "roughly 262
    // flops". THAT DESIGN DOES NOT FIT, and the failure is instructive:
    //
    //     instances   40,812 -> 50,400        (+9,588, not +262)
    //     utilisation   60.7% -> 78.7%
    //     result      GRT-0118, routing congestion too high
    //
    // The storage was never the cost. As localparams the shifts are CONSTANT,
    // so every requantisation shifter synthesises as fixed wiring -- a constant
    // shift is a wire permutation and costs nothing. Making them loadable turns
    // all 18 lanes (4 + 6 + 8) into real variable barrel shifters on ~21-bit
    // accumulators. I priced the registers and not what the registers do to the
    // datapath, which is the same mistake RTL-1 made.
    //
    // And the shifts did not need to be loadable in the first place. They only
    // change when the WEIGHTS change, the weights are 904 bytes of ROM, and new
    // weights are a respin regardless. Loadability is only worth flops for a
    // constant that can change WITHOUT a respin. Two can:
    //
    //   CLS_OFFSET      the decision boundary, re-chosen per deployment and per
    //                   false-alarm budget. Seeds an adder that already exists.
    //   SHAPE_GAP/DUR   the event-shaping rule, which trades event recall
    //                   against false alarms. Feeds two comparators.
    //
    // 42 bits, and neither touches the datapath's structure.
    //
    // SAFETY. The load is DOUBLE-BUFFERED and takes effect only at a frame
    // boundary. A shift that landed mid-frame would change the stem's shift
    // after the stem had already run and before the classifier did, and the
    // frame's score would be a chimera of two models with nothing marking it.
    // If no frame is in flight the transfer is immediate.
    //
    // DEFAULTS. Both registers reset to the generated constants, so a chip with
    // no host attached behaves exactly as the baked version did. The config
    // path is purely additive; it cannot make an unconfigured chip worse.
    localparam int CFG_W = 5 + 5 + 32;                      // 42
    localparam logic [CFG_W-1:0] CFG_DEFAULT =
        {SHAPE_M, SHAPE_N, CLS_OFFSET};

    reg [2:0] sck_sync, ld_sync;
    // DR0110 physical: cfg_sr[37], uio_in[3] were routed as ~0.2 pF long-wire nets
    // (extracted caps over the Liberty limit). cfg_xfer and sdi_q are pipeline
    // stages that cut those wires; the commit is delayed one clock to match, and
    // the host protocol (SDI held 4 clocks after SCK, LOAD after SCK low) has margin.
    reg [CFG_W-1:0] cfg_sr, cfg_live;
    reg cfg_pending, cfg_loaded;
    reg [CFG_W-1:0] cfg_xfer; reg cfg_pending_d, sdi_q;
    wire sck_rise = sck_sync[1] & ~sck_sync[2];
    wire ld_rise  =  ld_sync[1] & ~ld_sync[2];
    // Declared here rather than with the sensor instance below: the config
    // transfer is gated on them and this block comes first.
    wire sensor_in_frame;
    wire frame_start, frame_end, frame_valid, overrun, overrun_frame;

    always @(posedge clk) begin
        if (!rstn) begin
            sck_sync <= 3'b000; ld_sync <= 3'b000;
            cfg_sr <= CFG_DEFAULT; cfg_live <= CFG_DEFAULT;
            cfg_xfer <= CFG_DEFAULT; cfg_pending_d <= 1'b0; sdi_q <= 1'b0;
            cfg_pending <= 1'b0; cfg_loaded <= 1'b0;
        end else begin
            sdi_q <= uio_in[3]; cfg_xfer <= cfg_sr; cfg_pending_d <= cfg_pending;
            sck_sync <= {sck_sync[1:0], uio_in[2]};
            ld_sync  <= { ld_sync[1:0], uio_in[4]};
            if (sck_rise) cfg_sr <= {cfg_sr[CFG_W-2:0], sdi_q};
            if (ld_rise)  cfg_pending <= 1'b1;
            if (cfg_pending_d && (frame_start || !sensor_in_frame)) begin
                cfg_live    <= cfg_xfer;
                cfg_pending <= 1'b0; cfg_pending_d <= 1'b0;
                cfg_loaded  <= 1'b1;
            end
        end
    end

    wire signed [31:0] cfg_cls_offset = cfg_live[31:0];

    // ---- sensor ----------------------------------------------------------
    wire                      pix_valid;
    wire [8*IN_CH-1:0]        pix_data;
    wire [$clog2(IMG_H)-1:0]  pix_row;
    wire [$clog2(IMG_W)-1:0]  pix_col;
    aquafuse_sensor_if #(.IMG_H(IMG_H), .IMG_W(IMG_W), .IN_CH(IN_CH)) u_sensor (
        .clk(clk), .rst_n(rstn),
        .s_pclk(uio_in[0]), .s_vsync(uio_in[1]), .s_data(ui_in[8*IN_CH-1:0]),
        .core_ready(1'b1),
        .pix_valid(pix_valid), .pix_data(pix_data),
        .pix_row(pix_row), .pix_col(pix_col),
        .frame_start(frame_start), .frame_end(frame_end),
        .frame_valid(frame_valid), .overrun_sticky(overrun),
        .overrun_frame(overrun_frame), .in_frame(sensor_in_frame));

    // ---- stem: 8x8 stride 8, one input channel per cycle ------------------
    // Each input pixel lands in exactly one output cell because stride equals
    // kernel; see aquafuse_stem_accum for why that is what makes the whole
    // streaming stem fit in one output row of partial sums.
    // Explicitly UNSIGNED arithmetic. PAD_S and STEM_S are `int` localparams
    // and therefore signed; mixing them with unsigned pixel counters made the
    // whole expression signed and tripped a yosys frontend assert
    // (genrtlil.cc:2214). Widths are stated rather than inferred so the
    // signedness cannot drift back.
    localparam [7:0] PAD_U  = PAD_S[7:0];
    localparam [7:0] STEM_U = STEM_S[7:0];
    wire [7:0] row_u = {{(8-$clog2(IMG_H)){1'b0}}, pix_row};
    wire [7:0] col_u = {{(8-$clog2(IMG_W)){1'b0}}, pix_col};
    wire [7:0] srow_u = (row_u + PAD_U) / STEM_U;
    wire [7:0] scol_u = (col_u + PAD_U) / STEM_U;
    wire [$clog2(S_OW)-1:0] stem_col = scol_u[$clog2(S_OW)-1:0];
    wire [7:0] kr_u = row_u - STEM_U*srow_u + PAD_U;
    wire [7:0] kc_u = col_u - STEM_U*scol_u + PAD_U;
    wire [3:0] stem_kr = kr_u[3:0];
    wire [3:0] stem_kc = kc_u[3:0];

    wire [8*STEM_C-1:0] stem_w;
    // One combinational ROM PER LAYER, not one shared ROM. The three stages are
    // self-timed and can be MACing at the same time, so a single ROM would need
    // arbitration; three instances of a shared 8-lane ROM would trip- 
    // licate 1,296 B of constants. Per-layer ROMs at each layer's own lane
    // width total 904 B -- less than the padded shared one -- and every stage
    // gets its weight in ONE read. Address in, word out, no clock, 0 flops.
    aquafuse_rom_stem #(.COUT(STEM_C), .WORDS(64), .AW(6)) u_rom_stem (
        .addr({stem_kr[2:0], stem_kc[2:0]}), .word(stem_w));

    // mac_act is a SIGNED port. Driving it from an unsigned slice is the
    // signedness mismatch that tripped yosys at genrtlil.cc:2214 -- the
    // testbench drove it from a signed reg, so it only ever appeared here.
    //
    // THE SENSOR BYTE IS UNSIGNED 0..255 AND MUST BE BIASED, NOT REINTERPRETED.
    // The model's input is frames/127.5 - 1, a MONOTONIC ramp over the byte;
    // reading the byte as two's complement makes it a discontinuous sawtooth,
    // so byte 200 fed the network -56 where the model quantises it to +76.
    // Measured against the deployment model's own calibrated scale, over all
    // 256 byte values: reinterpretation is wrong by up to 134 codes on a +-127
    // range, and byte-128 by at most 6. Inverting the MSB IS byte-128, and
    // costs one inverter.
    wire signed [7:0] act_s = $signed({~pix_data[7], pix_data[6:0]});

    wire [$clog2(S_OW)-1:0] stem_rd_col;
    wire [8*STEM_C-1:0]     stem_byte;
    wire [32*STEM_C-1:0]    stem_bg, stem_acc;     // background and raw acc (12c)
    reg                     stem_flush;
    reg [$clog2(S_OW)-1:0]  flush_col;
    reg [$clog2(S_OH)-1:0]  stem_row;

    aquafuse_stem_accum #(.OUT_W(S_OW), .COUT(STEM_C), .ACC_W(STEM_ACC_W)) u_stem (
        .clk(clk), .rst_n(rstn),
        .mac_en(pix_valid), .mac_col(stem_col),
        .mac_act(act_s), .mac_wgt(stem_w),
        // RTL-8, FIXED 6 Sep. This read
        //     .row_clear(frame_start || (stem_flush && flush_col == S_OW-1))
        // -- one bank-wide wipe at the END of the 13-cycle row flush. But the
        // sensor streams throughout that flush, so at 4 core clocks per pixel
        // 21 of 5,184 pixels (columns 0-2 of image rows 4, 12, ... 52) were
        // MACed in and then wiped, and the chip convolved 5,163 pixels where
        // the model convolves 5,184. Measured: the logit disagreed with
        // reference.py on 4 of 32 golden frames, by up to 225 codes against a
        // smallest golden margin of 86. The loss was PCLK-RATE DEPENDENT --
        // exact at 16 clocks per pixel, wrong at 4 -- so a bring-up rig
        // clocking faster than deployment silently convolved a different image.
        //
        // Now each column is cleared AS IT IS READ, which cannot lose a pixel
        // at any rate down to one pixel per clock; see aquafuse_stem_accum.
        // The frame-start wipe stays: rows 52-53 accumulate into a stem row
        // that is never flushed, and without it those partial sums leak into
        // the next frame (RTL-6).
        .bank_clear(frame_start),
        .col_clear(stem_flush), .clear_col(flush_col),
        .rd_col(stem_rd_col), .rd_shift(SHIFT_STEM), .rd_relu(1'b1),
        .rd_sub(stem_bg), .rd_bias(BIAS_STEM), .rd_acc(stem_acc),
        .rd_byte(stem_byte));

    // ---- the background: EMA of the stem accumulator (DR 0093) ------------
    // Read and updated during the stem flush, one position per cycle, all four
    // lanes at once. The address is the position the flush is reading, so every
    // entry is touched exactly once per frame.
    // BG_BLOCK (aquafuse_chip.svh) picks the store: 0 is one entry per cell,
    // b >= 2 one per b x b block (the area option -- DR 0093's cost table).
    localparam int BG_N = S_OH * S_OW;                                 // 91
    wire bg_resynced;      // sticky: the background store had to realign
    // THE ADDRESSED STORE, not the shift register (DR 0093). The shift register
    // was 2.8% smaller in synthesis and unplaceable in hardening: q[i] <= q[i+1]
    // is ~5,400 flop-to-flop paths with no logic between them, the most
    // hold-critical structure there is, and the post-CTS resizer inserted over
    // 12,000 hold buffers that detailed placement could not fit (DPL-0036,
    // stream12c_8x4_r2). The addressed store writes computed data through a
    // multiplexer and has no such paths. Kept selectable, and recorded.
    localparam bit BG_FIFO = 1'b0;
    generate
        if (BG_BLOCK >= 2) begin : g_bg_block
            aquafuse_bg_block #(.S_OH(S_OH), .S_OW(S_OW), .B(BG_BLOCK),
                                .COUT(STEM_C), .W(EMA_W), .Q(EMA_Q)) u_bg (
                .clk(clk), .rst_n(rstn),
                .rd_en(stem_flush), .row(stem_row), .col(flush_col),
                .acc_in(stem_acc), .sub_out(stem_bg));
            assign bg_resynced = 1'b0;
        end else if (BG_FIFO) begin : g_bg_fifo
            aquafuse_bg_fifo #(.ENTRIES(BG_N), .COUT(STEM_C), .W(EMA_W),
                               .Q(EMA_Q)) u_bg (
                .clk(clk), .rst_n(rstn),
                .frame_start(frame_start), .rd_en(stem_flush),
                .acc_in(stem_acc), .sub_out(stem_bg),
                .resynced(bg_resynced));
        end else begin : g_bg_cell
            wire [$clog2(BG_N)-1:0] bg_addr =
                ($clog2(BG_N))'(stem_row) * ($clog2(BG_N))'(S_OW)
                + ($clog2(BG_N))'(flush_col);
            aquafuse_bg_store #(.ENTRIES(BG_N), .COUT(STEM_C), .W(EMA_W),
                                .Q(EMA_Q)) u_bg (
                .clk(clk), .rst_n(rstn),
                .rd_en(stem_flush), .addr(bg_addr),
                .acc_in(stem_acc), .sub_out(stem_bg));
            assign bg_resynced = 1'b0;      // an addressed store cannot slip
        end
    endgenerate
    assign stem_rd_col = flush_col;

    // An output row is complete once the last input row feeding it has landed.
    //
    // The `srow_u < S_OH_U` guard is NOT redundant. With H=54, pad=4, stride=8
    // the last stem output row is 6, fed by image rows 44..51, and rows 52-53
    // map to output row 7 -- which does not exist. The bottom-edge clause
    // (`pix_row == IMG_H-1`) flushed them anyway, so the stem emitted EIGHT
    // rows where the model has seven. Measured: the spurious row propagated as
    // 7 extra b1 outputs and 4 extra b2 outputs per frame, which accumulated
    // into the pool and moved the logit. The model discards those pixels; so
    // does this now.
    localparam [7:0] S_OH_U = S_OH[7:0];
    wire stem_row_done = pix_valid && (pix_col == IMG_W-1) &&
                         (((pix_row + PAD_S) % STEM_S) == STEM_S-1
                          || pix_row == IMG_H-1)
                         && (srow_u < S_OH_U);

    // Synchronous reset on the SYNCHRONISED rstn. Listing `negedge rst_n` in
    // the sensitivity while testing rstn in the body describes two different
    // resets and yosys rejects it ("Multiple edge sensitive events"). The
    // synchroniser exists precisely so downstream logic can be synchronous.
    always @(posedge clk) begin
        if (!rstn) begin
            stem_flush <= 1'b0; flush_col <= '0; stem_row <= '0;
        end else if (stem_row_done) begin
            stem_flush <= 1'b1; flush_col <= '0;
        end else if (stem_flush) begin
            if (flush_col == S_OW-1) begin
                stem_flush <= 1'b0; flush_col <= '0;
                stem_row <= stem_row + 1'b1;
            end else flush_col <= flush_col + 1'b1;
        end
        if (frame_start) stem_row <= '0;
    end

    // ---- two 3x3 stride-2 stages, each self-timed off its own input --------
    wire [3:0] w1_tap, w2_tap;
    wire [$clog2(STEM_C)-1:0] w1_ci;
    wire [$clog2(B1_CH)-1:0]  w2_ci;
    wire s1_valid, s2_valid, s1_busy, s2_busy;
    wire [$clog2(S_OH)-1:0]  s1_row;  wire [$clog2(S_OW)-1:0]  s1_col;
    wire [$clog2(B1_OH)-1:0] s2_row;  wire [$clog2(B1_OW)-1:0] s2_col;
    wire [8*B1_CH-1:0] s1_data;
    wire [8*B2_CH-1:0] s2_data;

    // im2col address: INPUT-CHANNEL-MAJOR, tap-minor -- k = ci*9 + tap.
    //
    // CORRECTED 3 Sep. This read `tap-major, input-channel-minor, matching the
    // order make_weight_rom emits`, and that was wrong in both halves: the
    // generator flattens (COUT, CIN, KH, KW) with reshape(COUT, -1), which is
    // ci-major, and the address here was tap-major. The chip therefore
    // convolved with a PERMUTED KERNEL -- a valid convolution of the wrong
    // weights, exactly the failure the comment claimed to be guarding against.
    // Verified exhaustively against the ROM contents: b1 216/216 and b2 432/432
    // match ci-major, 13/216 and 17/432 tap-major.
    //
    // Nothing caught this. tb_conv_stage feeds the stage its OWN synthetic
    // weights and never reads the ROMs, so only an end-to-end test against the
    // golden model could see it -- which is why tb_stream12_model now exists.
    wire [8*B1_CH-1:0] w1_data;
    wire [8*B2_CH-1:0] w2_data;
    // Widths are EXPLICIT. tap*IN_CH+ci reaches 35 for b1 and 53 for b2, so a
    // 4-bit product silently wraps and addresses the wrong kernel tap -- a
    // valid convolution of a permuted kernel, which no arithmetic check
    // catches. iverilog warned; the warning is the bug.
    wire [5:0] a_b1 = {4'b0, w1_ci} * 6'd9 + {2'b0, w1_tap};   // max 3*9+8 = 35
    wire [5:0] a_b2 = {3'b0, w2_ci} * 6'd9 + {2'b0, w2_tap};   // max 5*9+8 = 53
    aquafuse_rom_b1 #(.COUT(B1_CH), .WORDS(36), .AW(6)) u_rom_b1 (
        .addr(a_b1), .word(w1_data));
    aquafuse_rom_b2 #(.COUT(B2_CH), .WORDS(54), .AW(6)) u_rom_b2 (
        .addr(a_b2), .word(w2_data));

    aquafuse_conv_stage #(.IN_H(S_OH), .IN_W(S_OW), .IN_CH(STEM_C),
                          .OUT_CH(B1_CH), .STRIDE(2)) u_b1 (
        .clk(clk), .rst_n(rstn),
        .in_valid(stem_flush), .in_row(stem_row), .in_col(flush_col),
        .in_data(stem_byte),
        .w_tap(w1_tap), .w_ci(w1_ci), .w_data(w1_data),
        .cfg_shift(SHIFT_B1), .cfg_relu(1'b1),   // per-channel, CONSTANT: see CFG_W
        .cfg_bias(BIAS_B1),
        .out_valid(s1_valid), .out_row(s1_row), .out_col(s1_col),
        .out_data(s1_data), .busy(s1_busy));

    aquafuse_conv_stage #(.IN_H(B1_OH), .IN_W(B1_OW), .IN_CH(B1_CH),
                          .OUT_CH(B2_CH), .STRIDE(1)) u_b2 (
        .clk(clk), .rst_n(rstn),
        .in_valid(s1_valid), .in_row(s1_row[$clog2(B1_OH)-1:0]),
        .in_col(s1_col[$clog2(B1_OW)-1:0]), .in_data(s1_data),
        .w_tap(w2_tap), .w_ci(w2_ci), .w_data(w2_data),
        .cfg_shift(SHIFT_B2), .cfg_relu(1'b1),   // per-channel, CONSTANT: see CFG_W
        .cfg_bias(BIAS_B2),
        .out_valid(s2_valid), .out_row(s2_row), .out_col(s2_col),
        .out_data(s2_data), .busy(s2_busy));

    // ---- global average pool, then the REAL 8->1 classifier ---------------
    // PACKED, not an unpacked signed array: yosys converts an unpacked signed
    // memory to registers and then trips an internal signedness assert
    // (genrtlil.cc:2214). Packed storage with explicit $signed() at the point
    // of use synthesises cleanly and says what it means about signedness.
    //
    // Pool accumulates the B2 output over its POS positions; the average is a
    // shift because POS is a power of two, and b2 carries ReLU so the pooled
    // sum is never negative and the shift is unambiguous. host/aquafuse/stream/
    // reference.py pools the SAME way, so oracle and RTL agree by construction.
    //
    // The classifier is 8 INT8 MACs walked one channel per cycle after frame
    // end: 8 cycles out of 6,688, and it saves eight multipliers.
    //
    // THIS REPLACES A SIGN-TEST STUB (`alarm <= !pool[POOL_W-1]`), which tested
    // one of eight pooled channels with no learned weights. The stub made the
    // area real but meant the chip did not compute the network that every
    // quoted accuracy number describes, and it survived a full route.
    localparam int POS      = B2_OH * B2_OW;      // 4 x 7 = 28
    // POS_SH and CLS_W are gone with the pooling head: no shift, no
    // pooled-logit accumulator. POS remains because it names the number of
    // positions the 1x1 head now evaluates -- 28, not 8.

    // EVENT SHAPING: M ALARMS IN THE LAST N SCORED FRAMES.
    //
    // REPLACES close-gaps-then-duration, which replaced sustained-3, and each
    // replacement was measured rather than reasoned. One global rule chosen on
    // pooled calibration over 13 arms and read once on validation:
    //
    //     rule                          A2       false alarms / empty-hour
    //     raw alarm bit               0.8786                        763.7
    //     K-consecutive, best K = 13  0.7866                        108.1
    //     close G=16 then D=18        0.8657                         49.5
    //     2-of-21                     0.8831                         37.8
    //
    // Paired against close+duration, 2-of-21 is +0.0174 of A2 at 7.1 SE, better
    // in 12 of 13 arms, AND 11.7 fewer false alarms per hour. Against the RAW
    // bit it is a wash on A2 (+0.0046, 0.4 SE) while cutting false alarms 20x,
    // so it is close to free where close+duration cost 0.013 of A2.
    //
    // WHY THE PREVIOUS CHOICE WAS WRONG, on the record. close+duration and
    // 2-of-N measured as TIED ON RECALL, so I picked close+duration on cost --
    // two counters against a shift register -- and never scored A2 before
    // choosing. They were never tied on A2: a filter that suppresses isolated
    // alarms is almost purely a PRECISION gain, precision goes 0.908 -> 0.975,
    // and after that A2 = min(recall, precision) is recall-bound. Recall was
    // the wrong axis to compare on.
    //
    // N IS FIXED AT 21, M IS LOADABLE. The die failed GRT-0118 three times in
    // September at ~570 instances over what routes, so the window depth is a
    // constant and only the threshold rides the config word. That still carries
    // the trade worth carrying -- 2-of-21 against 3-of-21 is the recall/false-
    // alarm knob -- while a variable window would need a mask and its muxes.
    //
    // uo_out[0] stays the RAW per-frame alarm: it is what reference.py models
    // and what every corpus case scores. The shaped decision is additive on
    // uo_out[3].
    // Width constant taken FROM the generated header rather than restated, so
    // the RTL and aquafuse_shifts.svh cannot disagree about the window depth.
    // Declaring a second SHAPE_N here is a compile error, which is the point.
    // STREAM12C: N is the depth the accuracy was MEASURED at, generated from
    // the same run that chose it (aquafuse_chip.svh), not a 21 kept from 12b.
    localparam int SHAPE_DEPTH = SHAPE_N;
    localparam int SHAPE_W = 5;                 // M fits 5 bits
    reg [SHAPE_DEPTH-1:0]     alarm_hist;
    // Field order follows aquafuse_shifts.svh's DECLARATION order exactly, so
    // the payload is the generated header read top to bottom and there is no
    // second ordering for a host to get wrong. SHAPE_N rides the word as a
    // READ-ONLY echo so a host can confirm the depth it is talking to.
    wire [SHAPE_W-1:0]        cfg_m = cfg_live[CFG_W-1 -: SHAPE_W];
    /* verilator lint_off UNUSEDSIGNAL */
    wire [SHAPE_W-1:0]        cfg_n_echo = cfg_live[CFG_W-6 -: SHAPE_W];
    /* verilator lint_on UNUSEDSIGNAL */

    // THE WAKE BIT (STREAM12C, DR 0093): M of the last SHAPE_N raw bits, then
    // HELD for SHAPE_HOLD more frames after the popcount drops -- one 5-bit
    // down-counter. A3 counts false wake EPISODES, so a cluster of false alarms
    // held into one episode, and a visit whose alarm flickers held into one
    // wake, is what the hold buys; its duty is paid inside the budget because
    // the threshold is calibrated with the hold in place. The popcount and the
    // hold are computed below the head, from the bit the head is about to shift
    // in, so uo_out[3] is registered on the same edge as result_valid.
    reg [4:0]                 hold_cnt;
    reg                       wake;

    // THE COMPACT HEAD: a 1x1 convolution at every position, scored by a MAX.
    //
    // The deployed head average-pools 8 positions into B2_CH channels and runs
    // a Linear over them, which needs a B2_CH*POOL_W accumulator array (160
    // flops at POOL_W=20) and a per-channel FSM. This one needs neither: every
    // s2_valid carries all B2_CH channels of ONE position, so the dot product
    // is combinational and only the running maximum is state.
    //
    // MAX, not sum or mean, because frame_score in ml/train/tiny_detector.py is
    // a max over the grid: an animal occupies a few cells and averaging over 28
    // would bury it. The float model, the golden model and the silicon must
    // agree on this or the ROMs are correct and the answer is not.
    localparam int OBJ_W = 8 + 8 + $clog2(B2_CH) + 2;   // product + sum + sign
    reg signed [OBJ_W-1:0]    obj_max;
    reg                       obj_seen;
    // THE DECISION WAITS FOR STAGE 2 TO DRAIN, and must.
    //
    // Measured by tb_stream12b_logit: at 4 core clocks per pixel stage 2 had
    // emitted only 23 to 28 of its 28 positions when frame_end fired, so the
    // head took its maximum over a PARTIAL grid -- a well-formed logit over the
    // wrong number of positions. Four of twelve frames were wrong by -46, +76,
    // -14 and +34 codes. At 8 and 16 clocks per pixel it had drained and every
    // frame matched, which is why this is invisible to any single-rate test.
    //
    // At stride 2 stage 2 emitted 8 positions and always finished inside the
    // blanking interval. At stride 1 it emits 28, and the interval that sufficed
    // does not. So the trigger is not frame_end but "frame_end has been seen AND
    // all POS positions have arrived", whichever lands later -- at slow rates the
    // positions finish first, at fast rates frame_end does.
    //
    // This REPLACES the claim in an earlier revision of this file that the
    // compact head lets the minimum blanking drop from 9 core clocks to 1. The
    // head itself needs one cycle; the requirement did not disappear, it moved
    // upstream to the stage -- and it got THIRTY TIMES LARGER.
    //
    // MEASURED MINIMUM VERTICAL BLANKING: 269 CORE CLOCKS at 4 core clocks per
    // pixel, by bisection in tb_stream12b_logit (268 fails, 269 passes). The
    // deployed arm's figure is 9. Below the boundary a frame yields NO
    // result_valid rather than a wrong one, because frame_start clears the
    // pending decision -- loud, not silent, which is the right way round.
    //
    // Deployment has ~1e6 core clocks between frames at 15 fps and is nowhere
    // near this. A bring-up rig clocking fast is, so the number belongs in the
    // host contract next to the deployed arm's 9.
    reg [$clog2(POS+1)-1:0]   obj_n;
    reg                       fe_pending;
    reg                       alarm, result_valid;

    wire [8*B2_CH-1:0] obj_word;
    aquafuse_rom_obj #(.CIN(B2_CH)) u_rom_obj (.word(obj_word));

    // Combinational dot product of the arriving position against the head.
    // s2_data and obj_word use the SAME MSB-first lane order, so lane l of each
    // is channel l; reversing one silently scores the wrong channels.
    // THE BOUNDARY USES THE DEPLOYED SIGN CONVENTION, and it has to.
    //
    // The deployed head SEEDS its accumulator with cfg_cls_offset and tests the
    // SIGN of the result, so CLS_OFFSET holds -(logit(tau) - b)/(s_w*s_a) -- a
    // NEGATED threshold. derive_shifts.py generates it that way and
    // reference.py reads it that way. The first version of this head compared
    // `obj_max >= cfg_cls_offset` instead, reading the same register as a
    // POSITIVE threshold, which inverts the boundary silently: it synthesises,
    // it lints, and it scores a well-formed decision against the wrong sign.
    // Caught by porting reference.py, not by any test in the tree.
    //
    // So: add, then test the sign, exactly as the deployed head does. One
    // 32-bit adder, and the generated constant needs no reinterpretation.
    // THE BOUNDARY IS LATCHED PER FRAME, and it has to be on THIS head.
    //
    // The deployed head seeds `cls_acc <= cfg_cls_offset` at the start of its
    // walk, so it samples the register ONCE, at a defined instant, and a config
    // load afterwards cannot reach that frame's answer. This head read
    // `cfg_cls_offset` COMBINATIONALLY at the instant the decision is taken --
    // and that instant is AFTER `sensor_in_frame` falls, because stage 2 at
    // stride 1 emits 28 positions and spills past frame_end.
    //
    // The config block commits on `cfg_pending && (frame_start ||
    // !sensor_in_frame)`, which is correct and is byte-identical to the deployed
    // arm's. But "the frame boundary" is the SENSOR's boundary, and on this arm
    // the frame is still being scored when it passes. So a threshold written
    // while a frame was in flight landed inside this head's drain window and
    // changed THAT frame's score -- the exact defect the contract's
    // double-buffering exists to prevent, reintroduced downstream of it.
    //
    // Measured by porting tb_stream12_config, which the B datapath had never
    // been run against: frame B, loaded halfway through, answered with the NEW
    // boundary. The deployed arm passes the same case with the same config
    // timing -- the diagnostic shows cfg_live going live after 1 result_valid
    // pulse with sensor_in_frame=0 on BOTH arms -- because it latched and this
    // did not.
    //
    // Latched at frame_start, which is where this head already resets its state,
    // so the sampling instant is the one the rest of the frame's accumulation
    // agrees with. One 32-bit register.
    logic signed [31:0] cls_offset_q;
    logic signed [31:0] obj_logit;
    always_comb
        obj_logit = $signed({{(32-OBJ_W){obj_max[OBJ_W-1]}}, obj_max})
                  + $signed(cls_offset_q);

    logic signed [OBJ_W-1:0] obj_dot;
    always_comb begin
        obj_dot = OBJ_W'(BIAS_OBJ);      // the head's bias, seeded like the rest
        for (int l = 0; l < B2_CH; l++)
            obj_dot = obj_dot
                    + $signed(s2_data[8*(B2_CH-1-l) +: 8])
                      * $signed(obj_word[8*(B2_CH-1-l) +: 8]);
    end

    // NO POOLING TERM HERE, and that removes a whole class of defect with it.
    //
    // The deployed head's rounding comment records that a bare >>> is a FLOOR,
    // that floor biased every pooled channel low by ~0.5, and that the
    // resulting logit offset ranged -160.9 to +163.1 across nine models before
    // a constant adder fixed it. The compact head never averages, so there is
    // no shift, no rounding decision, and no model-dependent bias to correct.
    // host/aquafuse/stream/reference.py must mirror THIS, not the pooled form.


    // ---- the temporal head (TEMPORAL_K > 1), DR 0093 ----------------------
    // The frame's 28 head logits are written as they arrive; once the last is
    // in, the head runs its 9K-tap convolution per cell (756 cycles at K = 3)
    // and the DECISION waits for it. Without the head the decision is taken the
    // moment the grid is complete, exactly as 12b did.
    localparam bit USE_T = (TEMPORAL_K > 1);
    wire frame_ready = fe_pending && (obj_n == POS[$clog2(POS+1)-1:0]);
    wire t_done;
    wire signed [31:0] t_logit;
    reg  t_seen;
    reg  signed [31:0] cls_t;
    generate
        if (USE_T) begin : g_t
            aquafuse_temporal_head #(.GH(B2_OH), .GW(B2_OW), .K(TEMPORAL_K),
                .IN_W(OBJ_W), .MW(OBJ_T_W), .OBJ_SH(OBJ_SH),
                .T_W(T_TAPS), .T_B(T_BIAS)) u_t (
                .clk(clk), .rst_n(rstn),
                .wr_en(s2_valid),
                .wr_idx(($clog2(POS))'(s2_row) * ($clog2(POS))'(B2_OW)
                        + ($clog2(POS))'(s2_col)),
                .wr_val(obj_dot),
                .start(frame_ready && !frame_start && !s2_valid && !frame_end),
                .done(t_done), .logit(t_logit));
        end else begin : g_no_t
            assign t_done  = 1'b0;
            assign t_logit = '0;
        end
    endgenerate
    // The decision fires on the head's done pulse, or -- without a head -- in
    // the cycle the grid completes, with 12b's priority (a frame_start in that
    // cycle aborts it; see the blanking note below).
    wire decide = USE_T ? t_done
                        : (frame_ready && !frame_start && !s2_valid && !frame_end);
    wire signed [31:0] dec_logit = USE_T ? (t_logit + cls_t) : obj_logit;
    wire               dec_seen  = USE_T ? t_seen : obj_seen;
    reg  signed [31:0] score;            // the frame's max-cell logit, pre-offset

    // The raw bit this frame will shift in, the window it makes, its popcount
    // at FRAME rate (one small adder tree, 15 times a second), and the wake.
    wire                      raw_bit   = dec_seen && !dec_logit[31];
    wire [SHAPE_DEPTH-1:0]    hist_next = {alarm_hist[SHAPE_DEPTH-2:0], raw_bit};
    integer                   pc_i;
    reg [SHAPE_W-1:0]         count_next;
    always @* begin
        count_next = '0;
        for (pc_i = 0; pc_i < SHAPE_DEPTH; pc_i = pc_i + 1)
            count_next = count_next + {{(SHAPE_W-1){1'b0}}, hist_next[pc_i]};
    end
    wire sus_next = (cfg_m != '0) && (count_next >= cfg_m);

    always @(posedge clk) begin
        if (!rstn) begin
            obj_max <= '0; obj_seen <= 1'b0;
            obj_n <= '0; fe_pending <= 1'b0;
            alarm <= 1'b0; result_valid <= 1'b0;
            alarm_hist <= '0;
            hold_cnt <= '0; wake <= 1'b0;
            t_seen <= 1'b0; cls_t <= '0; score <= '0;
            // Resets to the live value, which at reset IS the generated
            // constant, so an unconfigured chip behaves exactly as the baked
            // version did -- the same promise the config block makes.
            cls_offset_q <= cfg_cls_offset;
        end else begin
            result_valid <= 1'b0;
            if (frame_start) begin
                // MINIMUM VERTICAL BLANKING: 9 CORE CLOCKS, and this line is
                // why. frame_start clears cls_run, so a VSYNC rise that lands
                // while the classifier is still walking its eight channels
                // ABORTS that frame's score and no result_valid is emitted --
                // silently. Measured 6 Sep by sweeping tb_stream12_btb: at 8
                // core clocks of blanking, 12 driven frames produce ONE result
                // and no error of any kind; at 9 they produce twelve. The
                // number is the classifier's own 8 MAC cycles plus one.
                //
                // Deployment is nowhere near this -- 15 fps leaves ~1.75M core
                // clocks between frames -- but the requirement was undocumented,
                // and a bring-up rig that violates it sees a chip that has
                // simply stopped answering. `btb_min` in the corpus pins the
                // boundary so a slower pipeline cannot move it unnoticed.
                obj_max <= '0; obj_seen <= 1'b0;
                obj_n <= '0; fe_pending <= 1'b0;
                cls_offset_q <= cfg_cls_offset;   // sample once, per frame
            end else if (s2_valid) begin
                // Running MAX over the 28 positions. obj_seen makes the first
                // position seed the maximum rather than compete with a reset
                // zero: every score can be negative, and seeding at zero would
                // silently floor the frame score at 0 and only ever show up as
                // a weak result on quiet frames.
                if (!obj_seen || obj_dot > obj_max) obj_max <= obj_dot;
                obj_seen <= 1'b1;
                if (obj_n != POS[$clog2(POS+1)-1:0]) obj_n <= obj_n + 1'b1;
            end else if (frame_end) begin
                // Only a frame the sensor vouches for may produce an answer. A
                // frame with a hole yields a well-formed score for pixels that
                // were never captured.
                //
                // LATCHED, not acted on. Stage 2 may still be emitting
                // positions; the decision is taken below once both this and the
                // full grid have arrived.
                if (frame_valid) fe_pending <= 1'b1;
            end else if (frame_ready) begin
                fe_pending <= 1'b0;
                // latched for the temporal head's decision, which lands ~756
                // cycles later -- possibly after the next frame_start has
                // cleared obj_seen and resampled the offset
                t_seen <= obj_seen;
                cls_t  <= cls_offset_q;
            end
            // THE DECISION, outside the chain so the temporal head's done pulse
            // cannot be swallowed by a frame_start in the same cycle. Without
            // the head, `decide` carries the chain's priority itself.
            if (decide) begin
                score        <= USE_T ? t_logit
                              : $signed({{(32-OBJ_W){obj_max[OBJ_W-1]}}, obj_max});
                alarm        <= raw_bit;              // sign of the logit
                // Shifts the SAME bit the alarm takes, not a second expression
                // of it. The deployed version recomputed the sign here; two
                // copies of one decision is how they drift.
                alarm_hist   <= hist_next;
                // held for SHAPE_HOLD frames after the popcount last fired:
                // high now if it fires now, or if it fired within the last
                // SHAPE_HOLD frames (the counter as it stood before this one)
                wake         <= sus_next || (hold_cnt != '0);
                hold_cnt     <= sus_next ? 5'(SHAPE_HOLD)
                              : (hold_cnt != '0 ? hold_cnt - 5'd1 : 5'd0);
                result_valid <= 1'b1;
            end
        end
    end

    // See the PIN MAP at the top. uo_out[5] shifts the config register's MSB
    // out so a host can read back what it wrote -- the only way to prove on
    // hardware that the shift path works, and it costs a wire.
    // uo_out[3] is the WAKE: the popcount with its hold, the bit the host
    // wakes on and the rule the accuracy was measured with (DR 0093).
    // uo_out[7]: sticky -- the background store lost alignment (a frame cut
    // short) and realigned itself. The part kept working; the host may want
    // to know its background was reseeded in places.
    assign uo_out  = {bg_resynced, cfg_loaded, cfg_sr[CFG_W-1], overrun_frame,
                      wake, overrun, result_valid, alarm};
    assign uio_out = 8'h00;
    assign uio_oe  = 8'h00;      // sensor pins are inputs; nothing is driven

endmodule
